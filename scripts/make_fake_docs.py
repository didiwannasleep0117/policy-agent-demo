def make_pdf(path: Path, title: str, paras: list[str]) -> None:
    pdf = FPDF()
    pdf.add_page()
    pdf.add_font("noto", fname=FONT)
    pdf.set_font("noto", size=18)
    pdf.cell(0, 12, f"{title}", new_x="LMARGIN", new_y="NEXT", align="C")
    pdf.set_font("noto", size=10)
    pdf.cell(0, 8, COMPANY, new_x="LMARGIN", new_y="NEXT", align="C")
    pdf.ln(4)
    pdf.set_font("noto", size=12)
    for p in paras:
        pdf.multi_cell(0, 8, p)
        pdf.ln(2)
    pdf.output(str(path))


def make_docx(path: Path, title: str, paras: list[str]) -> None:
    d = docx.Document()
    d.add_heading(title, level=1)
    d.add_paragraph(COMPANY)
    for p in paras:
        d.add_paragraph(p)
    d.save(str(path))


def make_xlsx(path: Path) -> None:
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "特約商店"
    for row in STORES:
        ws.append(row)
    wb.save(str(path))


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (title, paras) in DOCS.items():
        p = OUT / name
        (make_pdf if name.endswith(".pdf") else make_docx)(p, title, paras)
    make_xlsx(OUT / "特約商店清單.xlsx")
    print("\n".join(sorted(x.name for x in OUT.iterdir())))


if __name__ == "__main__":
    main()
